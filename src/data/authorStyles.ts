/** 单次最多可同时参考的作家数（过多会导致风格互相冲突） */
export const MAX_ACTIVE_AUTHORS = 3;

/**
 * 生成注入 AI 的「名家笔法」prompt 片段。
 * 强调：只借鉴技法特征，禁止使用其作品专有名词、禁止复制原句。
 */
export function buildAuthorStylePrompt(authors: AuthorStyle[]): string {
  if (authors.length === 0) return "";
  let out = `\n\n【名家笔法参考（本轮写作参考）】\n请借鉴以下作家的写作技法来构思与落笔（学"怎么写"，不是搬"写了什么"）：\n`;
  for (const a of authors) {
    out += `\n■ ${a.name}（代表作${a.representative}）—— ${a.tagline}\n`;
    out += `  · 叙事结构：${a.narrative}\n`;
    out += `  · 语言句式：${a.language}\n`;
    out += `  · 节奏爽点：${a.pacing}\n`;
    out += `  · 擅长维度：${a.strengths.join("、")}\n`;
  }
  out += `\n【笔法使用约束（必须遵守）】\n`;
  out += `1. 只借鉴上述**技法层面**的特征：叙事结构、语言节奏、氛围营造、情绪调度、爽点安排；\n`;
  out += `2. 严禁使用这些作家作品中的任何专有名词（人物名、地名、势力、功法、法宝、称号、境界名等），所有名称必须自行原创；\n`;
  out += `3. 严禁复制或改写其作品的任何原句，所有文字必须完全原创，只学"笔法"不搬"内容"；\n`;
  out += `4. 若同时参考多位作家，请把他们的技法自然融合成统一的文风，不要机械拼接或风格跳变。`;
  return out;
}
